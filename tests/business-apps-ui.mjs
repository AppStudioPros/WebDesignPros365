import { chromium, expect } from 'playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.BUSINESS_APPS_TEST_URL || 'http://localhost:3004';
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const program = {title:'Land acquisition workspace',description:'Fictional sample properties for testing.',view:'board',fields:[{id:'property',label:'Property',type:'text',options:[]},{id:'stage',label:'Stage',type:'select',options:['Sourcing','Due diligence','Under contract']},{id:'price',label:'Asking price',type:'currency',options:[]},{id:'date',label:'Review date',type:'date',options:[]}],records:[{id:'cedar',values:['Cedar Ridge','Due diligence','425000','2026-12-03']},{id:'willow',values:['Willow Creek','Sourcing','180000','2026-12-04']}]};
let available=true, mode='success', posted=[], release;
await page.route('**/api/business-apps', async route => {
 if(route.request().method()==='GET')return route.fulfill({json:{available}});
 const input=route.request().postDataJSON(); posted.push(input);
 if(mode==='error')return route.fulfill({status:502,json:{error:'Generation unavailable for this test.'}});
 if(mode==='invalid')return route.fulfill({json:{message:'Invalid result',program:{...program,fields:[]}}});
 if(mode==='delayed')await new Promise(resolve=>{release=resolve;});
 const next=input.current ? {...input.current,fields:[...input.current.fields,{id:'county',label:'County',type:'text',options:[]}],records:input.current.records.map(r=>({...r,values:[...r.values,'Denver County']}))} : structuredClone(program);
 await route.fulfill({json:{message:'Your sample program is ready.',program:next}}).catch(()=>{});
});
try {
 await page.goto(`${base}/business-applications`,{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Acquisitions & land',exact:true}).click();
 await expect(page.getByRole('heading',{name:program.title,exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Edit Cedar Ridge',exact:true}).click();
 await page.getByLabel('Asking price (USD)',{exact:true}).fill('450000');
 await page.getByRole('button',{name:'Save record',exact:true}).click();
 await page.getByRole('button',{name:'Table',exact:true}).click();
 await expect(page.getByRole('table')).toContainText('$450,000');
 await page.getByRole('button',{name:'Add record',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Property',{exact:true}).fill('Pine Valley');
 await dialog.getByLabel('Stage',{exact:true}).selectOption('Sourcing');
 await dialog.getByLabel('Asking price (USD)',{exact:true}).fill('290000');
 await dialog.getByLabel('Review date',{exact:true}).fill('2026-12-05');
 await dialog.getByRole('button',{name:'Add record',exact:true}).click();
 await expect(page.locator('tbody tr')).toHaveCount(3);
 await page.locator('#ai-business-prompt').fill('Add a county field and keep existing values.');
 await page.getByRole('button',{name:'Build or update workspace',exact:true}).click();
 await expect(page.getByRole('columnheader',{name:'County',exact:true})).toBeVisible();
 assert.equal(posted[1].current.records[0].values[2],'450000');
 await expect(page.getByRole('table')).toContainText('Pine Valley');
 await page.getByRole('button',{name:'Save preview',exact:true}).click();
 await page.reload({waitUntil:'networkidle'});
 await expect(page.getByRole('button',{name:'Saved locally',exact:true})).toBeVisible();
 await expect(page.getByRole('table')).toContainText('Pine Valley');
 mode='error';
 await page.locator('#ai-business-prompt').fill('Change the title');
 await page.getByRole('button',{name:'Build or update workspace',exact:true}).click();
 await expect(page.locator('#workspace-demo').getByRole('alert')).toContainText('Generation unavailable');
 await expect(page.getByRole('table')).toContainText('Pine Valley');
 mode='invalid';
 await page.getByRole('button',{name:'Build or update workspace',exact:true}).click();
 await expect(page.locator('#workspace-demo').getByRole('alert')).toContainText('could not be loaded');
 await expect(page.getByRole('table')).toContainText('Pine Valley');
 await page.getByRole('button',{name:'Agenda',exact:true}).click();
 await expect(page.getByRole('button',{name:'Edit Pine Valley',exact:true})).toBeVisible();
 await fs.mkdir('/workspace/shared/business-applications',{recursive:true});
 for(const width of [1440,1024,768,390,360]){
  await page.setViewportSize({width,height:1000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`Overflow at ${width}`);
 }
 await page.screenshot({path:'/workspace/shared/business-applications/ai-program-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('button',{name:'Board',exact:true}).click();
 await page.screenshot({path:'/workspace/shared/business-applications/ai-program-desktop.png',fullPage:true});
 mode='delayed';
 await page.locator('#ai-business-prompt').fill('Make another change');
 await page.getByRole('button',{name:'Build or update workspace',exact:true}).click();
 await expect(page.getByRole('button',{name:'Build or update workspace',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Reset preview',exact:true}).click();
 release?.();
 await expect(page.getByRole('heading',{name:program.title,exact:true})).toHaveCount(0);
 available=false;
 await page.reload({waitUntil:'networkidle'});
 await expect(page.getByRole('button',{name:'Explore guided samples',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Explore guided samples',exact:true}).click();
 await page.getByRole('button',{name:'Require approval above $250,000',exact:true}).click();
 await expect(page.getByText('Approval flagged',{exact:true})).toHaveCount(2);
 assert.deepEqual(errors,[]);
 console.log('PASS: generated UI with mocked provider: create/edit/add/follow-up, preserve on errors, save/restore/reset, table/board/agenda, 5 responsive widths, missing-key fallback, guided regression.');
} finally { await browser.close(); }
